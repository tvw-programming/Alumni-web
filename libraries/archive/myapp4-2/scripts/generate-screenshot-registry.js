#!/usr/bin/env node
/**
 * Scans src/components/<domain> for every component folder and generates:
 *   1. src/screenshotHarness/registry.generated.tsx — imports every
 *      `<Component>Usage` export and maps it to a "<domain>-<Component>" key.
 *   2. scripts/screenshots-manifest.json — a plain JSON list of the same
 *      keys, read by capture-screenshots.js (kept dependency-free: no need
 *      to parse TypeScript from plain Node).
 *
 * A component folder is any immediate subdirectory of a domain folder whose
 * index.ts re-exports `export { <Folder>Usage } from './<Folder>.usage';` —
 * that pattern is universal across every domain in this library, so no
 * per-domain special-casing is needed.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const COMPONENTS_DIR = path.join(ROOT, 'src/components');
const DOMAINS = [
  'agritech', 'ecommerce', 'education', 'enterprise', 'fintech', 'fitness',
  'gaming', 'healthcare', 'iot', 'media', 'realestate', 'social',
  'transportation', 'travel',
];
const SKIP_DIRS = new Set(['theme', 'types', 'primitives']);

/** A folder counts as a component folder if it has `index.ts` and a `*.usage.tsx`. */
function findComponentFolders(domain) {
  const domainDir = path.join(COMPONENTS_DIR, domain);
  if (!fs.existsSync(domainDir)) {
    console.warn(`[generate-screenshot-registry] Domain not found, skipping: ${domain}`);
    return [];
  }
  return fs
    .readdirSync(domainDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !SKIP_DIRS.has(entry.name))
    .map((entry) => entry.name)
    .filter((name) => {
      const usageFile = path.join(domainDir, name, `${name}.usage.tsx`);
      const indexFile = path.join(domainDir, name, 'index.ts');
      return fs.existsSync(usageFile) && fs.existsSync(indexFile);
    })
    .sort();
}

const manifest = [];
const importLines = [];
const entryLines = [];

for (const domain of DOMAINS) {
  const components = findComponentFolders(domain);
  for (const component of components) {
    const usageExportName = `${component}Usage`;
    const localAlias = `${domain}__${component}`;
    const key = `${domain}-${component}`;
    importLines.push(`import { ${usageExportName} as ${localAlias} } from '@ui/${domain}';`);
    entryLines.push(`  '${key}': ${localAlias},`);
    manifest.push({ domain, component, key, fileName: `${key}.jpg` });
  }
}

const registrySource = `/**
 * AUTO-GENERATED by scripts/generate-screenshot-registry.js — do not edit.
 * Regenerate with: node scripts/generate-screenshot-registry.js
 */
import React from 'react';

${importLines.join('\n')}

export const SCREENSHOT_REGISTRY: Record<string, React.ComponentType> = {
${entryLines.join('\n')}
};

export type ScreenshotKey = keyof typeof SCREENSHOT_REGISTRY;
`;

const harnessDir = path.join(ROOT, 'src/screenshotHarness');
fs.mkdirSync(harnessDir, { recursive: true });
fs.writeFileSync(path.join(harnessDir, 'registry.generated.tsx'), registrySource);
fs.writeFileSync(path.join(__dirname, 'screenshots-manifest.json'), JSON.stringify(manifest, null, 2));

console.log(`[generate-screenshot-registry] Discovered ${manifest.length} components across ${DOMAINS.length} domains.`);
console.log('[generate-screenshot-registry] Wrote src/screenshotHarness/registry.generated.tsx');
console.log('[generate-screenshot-registry] Wrote scripts/screenshots-manifest.json');
